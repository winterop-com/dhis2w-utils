"""The single `dhis2_cli` MCP tool: run the `dhis2` CLI as a subprocess.

Small local models cannot afford the full `dhis2w-mcp` server's ~337 typed tools (≈50-65k
tokens of schema loaded up front). This module exposes ONE tool instead: the model discovers
the command surface progressively with `--help` and runs commands with `--json`. Everything
stays on the host — the bridge spawns the local `dhis2` binary and never sends data anywhere.

`READ_ONLY_COMMANDS` is the allowlist consulted when `DHIS2_MCP_READONLY=1`: a fail-closed
set of read-only command paths generated by introspecting the Typer/Click command tree
(identical across the v41/v42/v43 plugin trees). `tests/test_cli_bridge.py` re-derives it from
the live tree so it cannot silently drift.
"""

